// Phase 8 P8-1 — pure notification mechanics.
//
// This module is a REUSABLE primitive layer, mirroring base44/shared/health/:
//   - NO Base44 SDK, NO UI, NO embeddings, NO LLM, NO randomness, NO host APIs.
//   - Every decision is a deterministic function of its inputs.
//
// MindVault-specific entity loading and finding generation live in the binding:
// base44/shared/notification/mindvaultNotifications.ts (+ computeNotifications).
//
// EPISODE MODEL (approved architecture):
//   - A row is an immutable EPISODE: created once per continuous occurrence of
//     a condition, never reopened, never deleted.
//   - dedupe_key identifies the finding/subject — not the episode, not the
//     recipient. Episode identity is (dedupe_key, recipient_user_id).
//   - Dismissed while the condition stays true -> suppressed (no new row).
//   - Condition clears -> resolved_at is set (open rows become 'resolved';
//     dismissed rows keep status but gain resolved_at, ending the episode).
//   - Condition re-enters after a clear -> a NEW episode with a fresh
//     triggered_at. A genuinely new occurrence always notifies again.
//   - Recipient churn -> the old recipient's episode is closed and a new
//     recipient episode is created, without changing the subject identity.

import { assessContinuityExposure } from "../health/continuityExposure.ts";
import type { ExposureSeverity } from "../health/types.ts";

export const DAY_MS = 86_400_000;

export type NotificationKind =
  | "review_due_soon"
  | "review_overdue"
  | "source_failure"
  | "gap_actionable"
  | "process_governance"
  | "key_person"
  // Reserved for later increments — never generated by P8-1:
  | "draft_stuck"
  | "continuity_drop";

/** The six kinds P8-1 generates. */
export const P8_1_KINDS: NotificationKind[] = [
  "review_due_soon",
  "review_overdue",
  "source_failure",
  "gap_actionable",
  "process_governance",
  "key_person",
];

export type FindingSeverity = "info" | "needs_attention" | "urgent";

export const GOVERNANCE_FINDINGS = [
  "missing_owner",
  "missing_sme",
  "missing_review_cadence",
  "criticality_unset",
] as const;
export type GovernanceFinding = (typeof GOVERNANCE_FINDINGS)[number];

// --- dedupe identity ------------------------------------------------------

export function makeDedupeKey(
  kind: NotificationKind,
  finding: string | null | undefined,
  refId: string,
): string {
  return kind === "process_governance"
    ? `process_governance:${finding || "unknown"}:${refId}`
    : `${kind}:${refId}`;
}

export function pairKey(dedupeKey: string, recipientUserId: string): string {
  return `${dedupeKey}::${recipientUserId}`;
}

// --- cooldowns ------------------------------------------------------------
// Entry-only kinds send once per episode (no key). Only kinds with an explicit
// reminder cadence ever remind.

export const REMINDER_COOLDOWN_DAYS: Partial<Record<NotificationKind, number>> = {
  review_overdue: 7,
  process_governance: 7,
};

export function reminderEligible(
  lastSentAt: string | null | undefined,
  cooldownDays: number | undefined,
  nowMs: number,
): boolean {
  if (!cooldownDays || cooldownDays <= 0) return false;
  if (!lastSentAt) return true;
  const t = Date.parse(lastSentAt);
  if (Number.isNaN(t)) return true;
  return nowMs >= t + cooldownDays * DAY_MS;
}

// --- severity mapping (reuses Phase 7 — never a second table) -------------

export function severityFromExposureSeverity(sev: ExposureSeverity): FindingSeverity {
  if (sev === "severe") return "urgent";
  if (sev === "moderate") return "needs_attention";
  return "info";
}

/**
 * Overdue-review severity, derived by calling the Phase 7 exposure primitive
 * with only criticality + overdue freshness varying (all other inputs neutral).
 * There is deliberately no second criticality->severity table here.
 */
export function overdueSeverityForCriticality(
  criticality: string | null | undefined,
): FindingSeverity {
  const exposures = assessContinuityExposure({
    criticality,
    coverageState: "documented_verified",
    worstUsableFreshness: "overdue",
    ownerPresent: true,
    smePresent: true,
    openGapCount: 0,
    hasPromotedGap: false,
    reviewCadenceResolved: true,
  });
  const overdue = exposures.find((e) => e.kind.startsWith("overdue_review"));
  return severityFromExposureSeverity(overdue ? overdue.severity : "info");
}

// --- recipient resolution ---------------------------------------------------

/**
 * First valid id in an ordered candidate chain. Invalid/dead ids fall through;
 * the caller decides the fallback (typically: all admins). Never invents
 * relationships — the chain must be built from schema-present fields only.
 */
export function pickFirstPresent(
  chain: Array<string | null | undefined>,
  validUserIds: Set<string>,
): string | null {
  for (const id of chain) {
    if (id && validUserIds.has(id)) return id;
  }
  return null;
}

// --- guarded recipient actions (decision core) ------------------------------

export interface ActingUser {
  id: string;
  role?: string | null;
}

export interface NotificationRowLike {
  id: string;
  dedupe_key: string;
  status: string;
  recipient_user_id: string;
  created_date?: string | null;
  triggered_at?: string | null;
  last_sent_at?: string | null;
  next_eligible_at?: string | null;
  read_at?: string | null;
  resolved_at?: string | null;
}

export function canAccessNotification(
  user: ActingUser | null | undefined,
  row: Pick<NotificationRowLike, "recipient_user_id">,
): boolean {
  if (!user || !user.id) return false;
  return user.role === "admin" || row.recipient_user_id === user.id;
}

export function canMarkRead(
  user: ActingUser | null | undefined,
  row: Pick<NotificationRowLike, "recipient_user_id">,
): { ok: true } | { ok: false; reason: "unauthorized" } {
  return canAccessNotification(user, row)
    ? { ok: true }
    : { ok: false, reason: "unauthorized" };
}

/**
 * Dismissal rules: recipient-or-admin only; only episodes that are still open
 * (or already dismissed — idempotent no-op). A resolved episode can no longer
 * be dismissed (the condition already cleared). Dismissal NEVER sets
 * resolved_at — that happens only when the underlying condition clears.
 */
export function canDismiss(
  user: ActingUser | null | undefined,
  row: Pick<NotificationRowLike, "recipient_user_id" | "status" | "resolved_at">,
):
  | { ok: true; noop: boolean }
  | { ok: false; reason: "unauthorized" | "already_resolved" } {
  if (!canAccessNotification(user, row)) return { ok: false, reason: "unauthorized" };
  if (row.resolved_at || row.status === "resolved") {
    return { ok: false, reason: "already_resolved" };
  }
  return { ok: true, noop: row.status === "dismissed" };
}

// --- reconciliation plan ---------------------------------------------------

export interface FindingDraft {
  kind: NotificationKind;
  finding: string | null;
  severity: FindingSeverity;
  dedupeKey: string;
  recipientUserId: string;
  clientScope: string;
  title: string;
  message: string;
  actionLabel: string;
  actionHref: string;
  operationalProcessId: string | null;
  sourceId: string | null;
  knowledgeGapId: string | null;
}

export interface PlannedCreate {
  draft: FindingDraft;
  reason: "first_detection" | "new_episode";
}

export interface ReconcilePlan {
  creates: PlannedCreate[];
  reminders: Array<{ id: string; last_sent_at: string; next_eligible_at: string | null }>;
  /** status 'resolved' added only when closing an OPEN episode; a dismissed episode just gains resolved_at. */
  resolves: Array<{ id: string; status?: "resolved"; resolved_at: string }>;
  /** subset of resolves whose subject remains active under a different recipient (recipient churn). */
  retargetedRowIds: string[];
  counts: {
    would_create: number;
    would_remind: number;
    would_resolve: number;
    would_retarget: number;
  };
}

function rowTs(r: NotificationRowLike): number {
  const t = Date.parse(r.triggered_at || r.created_date || "");
  return Number.isNaN(t) ? -Infinity : t;
}

/** Latest row per (dedupe_key, recipient) — the current episode of each pair. */
export function latestByPair(rows: NotificationRowLike[]): Map<string, NotificationRowLike> {
  const m = new Map<string, NotificationRowLike>();
  for (const r of rows || []) {
    if (!r || !r.dedupe_key || !r.recipient_user_id) continue;
    const pk = pairKey(r.dedupe_key, r.recipient_user_id);
    const cur = m.get(pk);
    if (!cur || rowTs(r) >= rowTs(cur)) m.set(pk, r);
  }
  return m;
}

/**
 * Deterministic diff of current findings (condition true) against existing
 * notification rows. Pure: writes nothing, mutates nothing.
 *   finding present, no current episode        -> create (first_detection)
 *   finding present, episode closed            -> create (new_episode)
 *   finding present, episode dismissed         -> suppress (no action)
 *   finding present, episode open same person  -> remind iff cooldown elapsed
 *   finding absent, episode still current      -> close it (resolve / dismiss-close);
 *       counted as would_retarget when the same subject is still active under
 *       another recipient (recipient churn), else would_resolve (condition clear).
 */
export function planReconciliation(
  findings: FindingDraft[],
  existingRows: NotificationRowLike[],
  nowMs: number,
): ReconcilePlan {
  const nowIso = new Date(nowMs).toISOString();
  const latest = latestByPair(existingRows);

  const findingByPair = new Map<string, FindingDraft>();
  for (const f of findings || []) {
    const pk = pairKey(f.dedupeKey, f.recipientUserId);
    if (!findingByPair.has(pk)) findingByPair.set(pk, f); // first wins on duplicates
  }
  const subjectsActive = new Set((findings || []).map((f) => f.dedupeKey));

  const plan: ReconcilePlan = {
    creates: [],
    reminders: [],
    resolves: [],
    retargetedRowIds: [],
    counts: { would_create: 0, would_remind: 0, would_resolve: 0, would_retarget: 0 },
  };

  for (const [pk, draft] of findingByPair) {
    const row = latest.get(pk);
    if (!row) {
      plan.creates.push({ draft, reason: "first_detection" });
      continue;
    }
    if (row.resolved_at) {
      plan.creates.push({ draft, reason: "new_episode" });
      continue;
    }
    if (row.status === "dismissed") continue; // suppressed while condition holds
    if (row.status !== "open") continue; // defensive: non-open, non-dismissed, non-closed
    const cooldown = REMINDER_COOLDOWN_DAYS[draft.kind];
    if (reminderEligible(row.last_sent_at, cooldown, nowMs)) {
      plan.reminders.push({
        id: row.id,
        last_sent_at: nowIso,
        next_eligible_at: cooldown
          ? new Date(nowMs + cooldown * DAY_MS).toISOString()
          : null,
      });
    }
  }

  for (const [pk, row] of latest) {
    if (findingByPair.has(pk)) continue;
    if (row.resolved_at) continue; // episode already closed — never reopened
    const close: { id: string; status?: "resolved"; resolved_at: string } = {
      id: row.id,
      resolved_at: nowIso,
    };
    if (row.status === "open") close.status = "resolved";
    plan.resolves.push(close);
    if (subjectsActive.has(row.dedupe_key)) {
      plan.retargetedRowIds.push(row.id); // churn: subject active under another recipient
    }
  }

  plan.counts = {
    would_create: plan.creates.length,
    would_remind: plan.reminders.length,
    would_resolve: plan.resolves.length - plan.retargetedRowIds.length,
    would_retarget: plan.retargetedRowIds.length,
  };
  return plan;
}

/** Row payload for a create — the ONLY shape used to open an episode. */
export function rowFromDraft(d: FindingDraft, nowMs: number): Record<string, unknown> {
  const nowIso = new Date(nowMs).toISOString();
  const cooldown = REMINDER_COOLDOWN_DAYS[d.kind];
  return {
    kind: d.kind,
    finding: d.finding,
    severity: d.severity,
    status: "open",
    recipient_user_id: d.recipientUserId,
    client_scope: d.clientScope,
    dedupe_key: d.dedupeKey,
    title: d.title,
    message: d.message,
    action_label: d.actionLabel,
    action_href: d.actionHref,
    operational_process_id: d.operationalProcessId,
    source_id: d.sourceId,
    knowledge_gap_id: d.knowledgeGapId,
    triggered_at: nowIso,
    last_sent_at: nowIso,
    next_eligible_at: cooldown ? new Date(nowMs + cooldown * DAY_MS).toISOString() : null,
    read_at: null,
    resolved_at: null,
    escalated: false,
  };
}

// --- client-scope-safe message construction --------------------------------
//
// Context values MUST be pre-vetted governed labels (source/gap/process/client
// names, dates). By construction these templates can never carry: another
// client's information, raw chunk content, reporter identity, raw employee
// question text, or internal technical state.

export interface NotificationContext {
  subjectTitle: string;
  processName?: string | null;
  clientName?: string | null; // only for client-scoped findings
  dueDate?: string | null;
  daysOverdue?: number | null;
}

function clientSuffix(ctx: NotificationContext): string {
  return ctx.clientName ? ` (Client: ${ctx.clientName})` : "";
}
function processSuffix(ctx: NotificationContext): string {
  return ctx.processName ? ` for "${ctx.processName}"` : "";
}

export function buildTitle(
  kind: NotificationKind,
  finding: string | null | undefined,
  ctx: NotificationContext,
): string {
  switch (kind) {
    case "review_due_soon":
      return `Review coming due: ${ctx.subjectTitle}`;
    case "review_overdue":
      return `Review overdue: ${ctx.subjectTitle}`;
    case "source_failure":
      return `Knowledge source needs repair: ${ctx.subjectTitle}`;
    case "gap_actionable":
      return `Recurring question needs documentation: ${ctx.subjectTitle}`;
    case "process_governance": {
      const pn = ctx.processName || ctx.subjectTitle;
      switch (finding) {
        case "missing_owner":
          return `Process needs an owner: ${pn}`;
        case "missing_sme":
          return `Process needs a subject-matter expert: ${pn}`;
        case "missing_review_cadence":
          return `Process needs a review schedule: ${pn}`;
        default:
          return `Process setup incomplete: ${pn}`;
      }
    }
    case "key_person":
      return `Continuity risk: single point of expertise on ${ctx.processName || ctx.subjectTitle}`;
    default:
      return ctx.subjectTitle;
  }
}

export function buildMessage(
  kind: NotificationKind,
  finding: string | null | undefined,
  ctx: NotificationContext,
): string {
  switch (kind) {
    case "review_due_soon":
      return `A review of "${ctx.subjectTitle}"${processSuffix(ctx)} is scheduled by ${
        ctx.dueDate ? ctx.dueDate.slice(0, 10) : "soon"
      }. Plan a review check-in so the knowledge stays current.${clientSuffix(ctx)}`;
    case "review_overdue": {
      const by = ctx.daysOverdue != null && ctx.daysOverdue > 0 ? ` by about ${ctx.daysOverdue} day${ctx.daysOverdue === 1 ? "" : "s"}` : "";
      return `A review of "${ctx.subjectTitle}"${processSuffix(ctx)} is due${by}. Run a review check-in to confirm the knowledge is current.${clientSuffix(ctx)}`;
    }
    case "source_failure":
      return `The indexed knowledge for "${ctx.subjectTitle}"${processSuffix(ctx)} failed to update and is not currently usable for answers. Re-index the source to restore it.${clientSuffix(ctx)}`;
    case "gap_actionable":
      return `Employees repeatedly ask about "${ctx.subjectTitle}"${processSuffix(ctx)} and the current knowledge does not fully answer it. Review the topic and update or add a source.${clientSuffix(ctx)}`;
    case "process_governance":
      switch (finding) {
        case "missing_owner":
          return `The process "${ctx.processName || ctx.subjectTitle}" has no assigned process owner. Assigning an owner is required before its governance can be completed.${clientSuffix(ctx)}`;
        case "missing_sme":
          return `The process "${ctx.processName || ctx.subjectTitle}" has no assigned subject-matter expert. Assign a primary expert so the knowledge has a clear owner of last resort.${clientSuffix(ctx)}`;
        case "missing_review_cadence":
          return `The process "${ctx.processName || ctx.subjectTitle}" has no review schedule. Set a review interval so its knowledge freshness can be tracked.${clientSuffix(ctx)}`;
        default:
          return `The process "${ctx.processName || ctx.subjectTitle}" has no criticality setting. Set a criticality so reviews and continuity risk can be prioritized.${clientSuffix(ctx)}`;
      }
    case "key_person":
      return `This process depends on a single subject-matter expert with no named backup, which puts continuity at risk. Naming a backup expert reduces the exposure. Keeping the documentation behind this dependency verified and current also helps.${clientSuffix(ctx)}`;
    default:
      return ctx.subjectTitle;
  }
}

export function actionFor(
  kind: NotificationKind,
  refs: { sourceId?: string | null; processId?: string | null },
): { label: string; href: string } {
  switch (kind) {
    case "review_due_soon":
    case "review_overdue":
      return { label: "Open the source", href: refs.sourceId ? `/training/${refs.sourceId}` : "/library" };
    case "source_failure":
      return { label: "Repair the source", href: refs.sourceId ? `/training/${refs.sourceId}` : "/admin" };
    case "gap_actionable":
      return { label: "Triage the knowledge gap", href: "/admin" };
    case "process_governance":
    case "key_person":
      return { label: "Open process continuity", href: "/continuity" };
    default:
      return { label: "Open the dashboard", href: "/continuity" };
  }
}